/**
 * Сколько запросов одновременно может дойти до обработчиков.
 *
 * Это потолок на число незавершённых запросов, а не на длину буфера очереди:
 * каждый такой запрос держит сокет, промис и замыкание. Смысл лимита —
 * сделать перегрузку явной (503 вместо Out of Memory), а не деградировать постепенно.
 */
export const ADMISSION_MAX_IN_FLIGHT = 200

/**
 * Сколько секунд клиенту ждать перед повтором. Значение совпадает с периодом
 * батча добавления: к моменту повтора свободные слоты обычно уже есть.
 */
export const ADMISSION_RETRY_AFTER_SECONDS = 10

/**
 * Под флудом 503-ки идут тысячами в секунду, и лог умирает вместе с процессом.
 * Поэтому в лог попадает не каждое отклонение, а одно на интервал — но само
 * число отклонений при этом считается всегда, иначе в логах будет недооценка
 * нагрузки.
 */
export const ADMISSION_LOG_INTERVAL_MS = 10_000
