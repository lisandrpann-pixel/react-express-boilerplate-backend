/**
 * Как часто разгружаем буфер добавлений.
 */
export const CREATE_BATCH_INTERVAL_MS = 10_000

/**
 * Сколько элементов отдаём одной командой.
 */
export const CREATE_BATCH_MAX = 500

/**
 * Потолок буфера.
 *
 * Если БД молчит и буфер не разгружается,
 * защищать память должен лимит, а не счётчик одновременных соединений —
 * запросы к тому моменту уже успели ответить.
 */
export const CREATE_BATCH_CAPACITY = 5_000

/** Что отдаём клиенту в заголовке Retry-After, чтобы он знал, когда проверить */
export const CREATE_BATCH_RETRY_AFTER_SECONDS = Math.ceil(
  CREATE_BATCH_INTERVAL_MS / 1000
)

/**
 * Как часто разгружаем линии, где клиент ждёт ответа: изменение и чтение.
 */
export const SYNC_BATCH_INTERVAL_MS = 1_000

/**
 * Сколько элементов отдаём одной командой.
 */
export const SYNC_BATCH_MAX = 500

/**
 * Потолок буфера синхронных линий.
 *
 * Для чтения раньше него сработает admission-лимит одновременных запросов,
 * но потолок остаётся страховкой: линия отвечает 503, а не копит долги.
 */
export const SYNC_BATCH_CAPACITY = 5_000
