/**
 * Сколько ответов держим одновременно.
 */
export const DEDUP_MAX_ENTRIES = 5_000

/**
 * Сколько живёт запись с ключом.
 *
 * Должно быть не меньше периода батча (сейчас запись синхронная, батча ещё
 * нет, плановый — 10 секунд). Если TTL окажется короче, повтор запроса
 * запустит новую работу и клиент получит не тот ответ, который уже видел.
 */
export const DEDUP_TTL_MS = 10_000

/**
 * Ограничение на длину Idempotency-Key. Заголовок без проверки уедет прямо в
 * ключ кэша: Node сам ограничивает заголовки примерно 8 КБ, но хранить
 * попросить клиента полкилобайтную строку — значит платить за это памятью.
 */
export const IDEMPOTENCY_KEY_MAX_LENGTH = 255

/**
 * Заголовок необязательный. Без него работает запасной путь по отпечатку
 * тела, который склеивает только параллельные дубли, но не защищает от повтора
 * позже.
 */
export const IDEMPOTENCY_HEADER = 'Idempotency-Key'
