/**
 * Сколько клиентов одновременно могут держать поток событий.
 *
 * Лимит свой, отдельный от admission: поток монтируется до admission и слот
 * обработчиков не занимает, поэтому ограничивать его нужно именно здесь —
 * иначе память и сокеты утекут без счётчика.
 */
export const SSE_MAX_CLIENTS = 100

/**
 * Пауза между heartbeat-комментариями.
 *
 * Без них молчащее соединение убивают прокси и таймауты keep-alive: клиент
 * примет обрыв за свой и начнёт переподключаться вхолостую.
 */
export const SSE_HEARTBEAT_MS = 15_000

/**
 * Через сколько миллисекунд клиенту переподключаться после обрыва.
 * Уходит в заголовок `retry` — его подхватывает EventSource.
 */
export const SSE_RETRY_MS = 3_000
